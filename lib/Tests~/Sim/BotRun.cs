    /// <summary>
    /// The Stage 07 bot: complete runs, headless, one row per floor in
    /// <c>artifacts/balance.csv</c>.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The bot reaches a battle exactly the way the game will: <see cref="RunSession"/>
    /// validates the bag, <see cref="SceneFlow"/> asks an <see cref="IBattleSessionFactory"/>
    /// for a session, the bot <b>steps that session and reads its frame</b>, and the result
    /// is settled back into the run. It never names a simulation type, so the same bot runs
    /// against the fake tomorrow and against a rebuilt battle next year.
    /// </para>
    /// <para>
    /// What the CSV is for: a per-floor picture of the tables. Outcome, reason, ticks, HP,
    /// kills and bia, across as many seeds as asked for, with the camp decisions counted.
    /// Reading a column tells you whether a floor is a wall or a formality — which is the
    /// input the balance pass (Stage 11) needs, and which a single hand-played floor cannot
    /// tell you.
    /// </para>
    /// </remarks>
    internal static class BotRun
    {
        private const string Header =
            "## ProjectSurvive bot balance run\n"
            + "## mode: kiting bot, greedy camp; one row per floor per seed\n"
            + "## generated by: tools/sim.ps1 --mode bot\n"
            + "seed,floor_index,floor_id,is_boss,outcome,end_reason,ticks,floor_seconds,"
            + "final_hp,max_hp,hp_percent,kills,currency_earned,bia,pieces_on_board,board_weight,"
            + "purchases,merges,placed,left_in_chest,build\n";

        internal static int Run(SimOptions options, IGameConfig config, TextWriter output)
        {
            var codec = new MessagePackBackpackSnapshotCodec();
            var rows = new StringBuilder(Header);
            var summaries = new List<RunSummary>(options.Seeds);
            int exitCode = 0;

            for (int i = 0; i < options.Seeds; i++)
            {
                uint seed = unchecked(options.Seed + (uint)i);
                RunSummary summary = PlayRun(seed, options, config, codec, rows, output);
                summaries.Add(summary);
                if (summary.Failed)
                {
                    exitCode = 2;
                    break;
                }
            }

            File.WriteAllText(options.OutputPath, rows.ToString(), new UTF8Encoding(false));
            output.WriteLine("balanceCsv=" + options.OutputPath);
            WriteSummary(options, summaries, output);
            return exitCode;
        }

        private static RunSummary PlayRun(
            uint seed,
            SimOptions options,
            IGameConfig config,
            IBackpackSnapshotCodec codec,
            StringBuilder rows,
            TextWriter output)
        {
            var summary = new RunSummary { Seed = seed, Build = options.Build.Name };
            var run = new RunSession(config, codec, seed);
            var flow = new SceneFlow(run, new EcsBattleSessionFactory(config));
            var bot = new KiteBot(options.Build.Engagement);
            var camp = new CampBot(config, options.Build);

            Result started = run.StartRun();
            if (started.IsFailure)
            {
                output.WriteLine("seed=" + seed.ToString(CultureInfo.InvariantCulture) + " runFailed=" + started.Error);
                summary.Failed = true;
                return summary;
            }

            int guard = 0;
            while (!run.IsRunOver)
            {
                if (guard++ > 64)
                {
                    // Five floors is five camp/battle pairs; more than this means a state
                    // the flow cannot leave, and a silent infinite bot run is worse than a
                    // failed one.
                    output.WriteLine("seed=" + seed + " flowStuck=" + run.FlowState);
                    summary.Failed = true;
                    return summary;
                }

                if (run.FlowState == RunFlowState.Camp)
                {
                    CampReport report = camp.PlayCamp(run);

                    Result<IBattleSession> entered = flow.EnterBattle();
                    if (entered.IsFailure)
                    {
                        output.WriteLine("seed=" + seed + " cannotStartFloor=" + entered.Error);
                        summary.Failed = true;
                        return summary;
                    }

                    summary.PendingPurchases = report.Purchases;
                    summary.PendingMerges = report.Merges;
                    summary.PendingPlaced = report.Placed;
                    summary.PendingLeftInChest = report.LeftInChest;
                    continue;
                }

                IBattleSession? session = flow.Battle;
                if (run.FlowState == RunFlowState.Battle && session is not null)
                {
                    // Captured before the settlement: a win advances the run's floor cursor,
                    // and the row must describe the floor that was fought.
                    FloorConfig? fought = run.CurrentFloor;
                    int steps = 0;
                    while (session.Phase == BattlePhase.Running)
                    {
                        if (steps++ >= options.MaxSteps)
                        {
                            output.WriteLine(
                                "seed=" + seed + " floorDidNotEnd=" + fought?.Id
                                + " steps=" + steps);
                            summary.Failed = true;
                            return summary;
                        }

                        flow.StepBattle(bot.Decide(session));
                    }

                    if (!session.TryGetResult(out BattleResult result))
                    {
                        output.WriteLine("seed=" + seed + " floorEndedWithoutResult=" + fought?.Id);
                        summary.Failed = true;
                        return summary;
                    }

                    Result<FloorSettlement> settled = flow.SettleBattle();
                    if (settled.IsFailure)
                    {
                        output.WriteLine("seed=" + seed + " settlementFailed=" + settled.Error);
                        summary.Failed = true;
                        return summary;
                    }

                    AppendRow(rows, seed, run, fought, result, settled.Value, summary);
                    summary.Add(settled.Value, result);

                    if (!options.Quiet)
                    {
                        output.WriteLine(string.Format(
                            CultureInfo.InvariantCulture,
                            "seed={0} floor={1} {2}/{3} ticks={4} hp={5} kills={6} bia={7}",
                            seed, settled.Value.FloorIndex, result.Outcome, result.EndReason,
                            result.SurvivedTicks, result.FinalHp, result.Kills, run.Wallet.Bia));
                    }

                    continue;
                }

                output.WriteLine("seed=" + seed + " unexpectedState=" + run.FlowState);
                summary.Failed = true;
                return summary;
            }

            summary.Hp = run.Hp;
            summary.Bia = run.Wallet.Bia;
            summary.FloorsCleared = run.FloorsCleared;
            summary.TotalFloors = run.TotalFloors;

            if (!options.Quiet)
            {
                output.WriteLine(string.Format(
                    CultureInfo.InvariantCulture,
                    "seed={0} run={1}/{2} cleared={3} hp={4} bia={5}",
                    seed, summary.FloorsCleared, summary.TotalFloors, summary.Cleared ? "cleared" : "ended",
                    run.Hp, run.Wallet.Bia));
            }

            return summary;
        }

        private static void AppendRow(
            StringBuilder rows,
            uint seed,
            RunSession run,
            FloorConfig? floor,
            BattleResult result,
            FloorSettlement settlement,
            RunSummary summary)
        {
            Backpack backpack = run.Backpack;
            int onBoard = 0;
            IReadOnlyList<BagPieceInstance> bags = backpack.Bags;
            for (int i = 0; i < bags.Count; i++)
            {
                if (bags[i].Zone == PieceZone.Board)
                {
                    onBoard++;
                }
            }

            IReadOnlyList<ItemInstance> items = backpack.Items;
            for (int i = 0; i < items.Count; i++)
            {
                if (items[i].Zone == PieceZone.Board)
                {
                    onBoard++;
                }
            }

            int maxHp = run.MaxHp;
            float hpPercent = maxHp > 0 ? (100f * result.FinalHp) / maxHp : 0f;

            rows.Append(seed.ToString(CultureInfo.InvariantCulture)).Append(',');
            rows.Append(settlement.FloorIndex.ToString(CultureInfo.InvariantCulture)).Append(',');
            rows.Append(floor?.Id ?? "").Append(',');
            rows.Append((floor?.IsBoss ?? false) ? "true" : "false").Append(',');
            rows.Append(result.Outcome.ToString()).Append(',');
            rows.Append(result.EndReason.ToString()).Append(',');
            rows.Append(result.SurvivedTicks.ToString(CultureInfo.InvariantCulture)).Append(',');
            rows.Append((floor?.DurationSeconds ?? 0f).ToString("0.##", CultureInfo.InvariantCulture)).Append(',');
            rows.Append(result.FinalHp.ToString(CultureInfo.InvariantCulture)).Append(',');
            rows.Append(maxHp.ToString(CultureInfo.InvariantCulture)).Append(',');
            rows.Append(hpPercent.ToString("0.##", CultureInfo.InvariantCulture)).Append(',');
            rows.Append(result.Kills.ToString(CultureInfo.InvariantCulture)).Append(',');
            rows.Append(result.CurrencyEarned.ToString(CultureInfo.InvariantCulture)).Append(',');
            rows.Append(run.Wallet.Bia.ToString(CultureInfo.InvariantCulture)).Append(',');
            rows.Append(onBoard.ToString(CultureInfo.InvariantCulture)).Append(',');
            rows.Append(backpack.BoardWeight.ToString("0.###", CultureInfo.InvariantCulture)).Append(',');
            rows.Append(summary.PendingPurchases.ToString(CultureInfo.InvariantCulture)).Append(',');
            rows.Append(summary.PendingMerges.ToString(CultureInfo.InvariantCulture)).Append(',');
            rows.Append(summary.PendingPlaced.ToString(CultureInfo.InvariantCulture)).Append(',');
            rows.Append(summary.PendingLeftInChest.ToString(CultureInfo.InvariantCulture)).Append(',');
            rows.Append(summary.Build).Append('\n');
        }

        private static void WriteSummary(SimOptions options, List<RunSummary> summaries, TextWriter output)
        {
            int runs = 0;
            int cleared = 0;
            var perFloor = new Dictionary<int, FloorStats>();

            foreach (RunSummary summary in summaries)
            {
                if (summary.Failed)
                {
                    continue;
                }

                runs++;
                if (summary.Cleared)
                {
                    cleared++;
                }

                foreach (KeyValuePair<int, FloorStats> entry in summary.PerFloor)
                {
                    if (!perFloor.TryGetValue(entry.Key, out FloorStats? stats))
                    {
                        stats = new FloorStats();
                        perFloor[entry.Key] = stats;
                    }

                    stats.Attempts++;
                    if (entry.Value.Wins > 0)
                    {
                        stats.Wins++;
                    }

                    stats.Ticks += entry.Value.Ticks;
                    stats.Kills += entry.Value.Kills;
                }
            }

            output.WriteLine("runs=" + runs.ToString(CultureInfo.InvariantCulture));
            output.WriteLine("runsCleared=" + cleared.ToString(CultureInfo.InvariantCulture));

            var keys = new List<int>(perFloor.Keys);
            keys.Sort();
            foreach (int key in keys)
            {
                FloorStats stats = perFloor[key];
                output.WriteLine(string.Format(
                    CultureInfo.InvariantCulture,
                    "floor={0} attempts={1} wins={2} meanTicks={3} meanKills={4}",
                    key,
                    stats.Attempts,
                    stats.Wins,
                    stats.Attempts > 0 ? (double)stats.Ticks / stats.Attempts : 0.0,
                    stats.Attempts > 0 ? (double)stats.Kills / stats.Attempts : 0.0));
            }
        }

        private sealed class RunSummary
        {
            internal uint Seed;

            internal bool Failed;

            internal int Hp;

            internal int Bia;

            internal int FloorsCleared;

            internal int TotalFloors;

            internal bool Cleared => TotalFloors > 0 && FloorsCleared >= TotalFloors;

            internal int PendingPurchases;

            internal int PendingMerges;

            internal int PendingPlaced;

            internal int PendingLeftInChest;

            internal string Build = BuildPlan.Default.Name;

            internal Dictionary<int, FloorStats> PerFloor { get; } = new Dictionary<int, FloorStats>();

            internal void Add(FloorSettlement settlement, BattleResult result)
            {
                if (!PerFloor.TryGetValue(settlement.FloorIndex, out FloorStats? stats))
                {
                    stats = new FloorStats();
                    PerFloor[settlement.FloorIndex] = stats;
                }

                stats.Attempts++;
                if (settlement.IsWin)
                {
                    stats.Wins++;
                }

                stats.Ticks += result.SurvivedTicks;
                stats.Kills += result.Kills;
            }
        }

        private sealed class FloorStats
        {
            internal int Attempts;

            internal int Wins;

            internal long Ticks;

            internal long Kills;
        }
    }
