using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using ProjectSurvive.Game.Presentation.Figure;
using ProjectSurvive.Game.Presentation.SpineActors;
using Spine;
using Spine.Unity;
using UnityEditor;
using UnityEngine;
using SpineAnimation = Spine.Animation;

namespace ProjectSurvive.Game.Editor
{
    /// <summary>
    /// Writes down everything the player skeleton contains, to <c>artifacts/spine/player-skeleton.md</c>.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The names of animations and skins are not in code anywhere — the profile names them and the
    /// view plays what the profile names — so before anything can be wired up the skeleton has to
    /// be read. This command is that reading, printed: bones, slots, every animation with its
    /// duration, every skin with its attachment count, the atlas pages and the shader each material
    /// actually uses.
    /// </para>
    /// <para>
    /// Editor API only (AGENTS 11): the asset is reached through the project's own resources, not by
    /// guessing a file layout, and the numbers come from the parsed skeleton rather than from the
    /// text of the .atlas file.
    /// </para>
    /// </remarks>
    public static class SpineDumpTool
    {
        private const string OutputFolder = "artifacts/spine";
        private const string OutputFileName = "player-skeleton.md";
        private const string SpineRuntimePackageJson = "Assets/Spine/package.json";

        [MenuItem("ProjectSurvive/Spine/1. Dump player skeleton", priority = 170)]
        public static void DumpPlayerSkeleton()
        {
            SkeletonDataAsset asset;
            string loadCode;
            if (!SpineSkeletonLoader.TryLoad(SpineAssetPaths.PlayerSkeletonData, out asset, out loadCode))
            {
                Debug.LogError("[SpineDumpTool] " + loadCode + ": could not load '" + SpineAssetPaths.PlayerSkeletonData + "'");
                return;
            }

            SkeletonData data = asset.GetSkeletonData(true);
            if (data == null)
            {
                Debug.LogError("[SpineDumpTool] " + SpineSkeletonLoader.InvalidCode + ": '" + asset.name + "' produced no SkeletonData");
                return;
            }

            string markdown = BuildReport(asset, data);

            string repositoryRoot = Path.GetFullPath(Path.Combine(Application.dataPath, "..", ".."));
            string folder = Path.Combine(repositoryRoot, OutputFolder);
            Directory.CreateDirectory(folder);
            string path = Path.Combine(folder, OutputFileName);
            File.WriteAllText(path, markdown, new UTF8Encoding(false));

            AssetDatabase.Refresh();
            Debug.Log("[SpineDumpTool] wrote " + path + " (" + data.Bones.Count + " bones, " +
                data.Slots.Count + " slots, " + data.Animations.Count + " animations, " +
                data.Skins.Count + " skins)");
        }

        private static string BuildReport(SkeletonDataAsset asset, SkeletonData data)
        {
            var text = new StringBuilder();
            text.AppendLine("# Player skeleton — " + data.Name);
            text.AppendLine();
            text.AppendLine("Generated by `ProjectSurvive/Spine/1. Dump player skeleton`.");
            text.AppendLine();
            text.AppendLine("| Fact | Value |");
            text.AppendLine("| --- | --- |");
            text.AppendLine("| asset | `" + AssetPath(asset) + "` |");
            text.AppendLine("| resource path | `" + SpineAssetPaths.PlayerSkeletonData + "` |");
            text.AppendLine("| skeleton data version | " + data.Version + " |");
            text.AppendLine("| spine-unity package | " + InstalledRuntimeVersion() + " |");
            text.AppendLine("| SkeletonDataAsset.scale | " + Float(asset.scale) + " |");
            text.AppendLine("| skeleton size | " + Float(data.Width) + " x " + Float(data.Height) + " |");
            text.AppendLine("| atlas assets | " + (asset.atlasAssets != null ? asset.atlasAssets.Length : 0) + " |");
            text.AppendLine();

            text.AppendLine("## Bones (" + data.Bones.Count + ")");
            text.AppendLine();
            for (int i = 0; i < data.Bones.Count; i++)
            {
                BoneData bone = data.Bones.Items[i];
                if (bone != null)
                {
                    text.AppendLine("- " + bone.Name);
                }
            }

            text.AppendLine();
            text.AppendLine("## Slots (" + data.Slots.Count + ")");
            text.AppendLine();
            for (int i = 0; i < data.Slots.Count; i++)
            {
                SlotData slot = data.Slots.Items[i];
                if (slot == null)
                {
                    continue;
                }

                text.AppendLine("- " + slot.Name +
                    " (bone " + (slot.BoneData != null ? slot.BoneData.Name : "?") +
                    ", setup attachment " + (string.IsNullOrEmpty(slot.AttachmentName) ? "(none)" : slot.AttachmentName) + ")");
            }

            text.AppendLine();
            text.AppendLine("## Animations (" + data.Animations.Count + ")");
            text.AppendLine();
            text.AppendLine("| Animation | Duration (s) |");
            text.AppendLine("| --- | --- |");
            for (int i = 0; i < data.Animations.Count; i++)
            {
                SpineAnimation animation = data.Animations.Items[i];
                if (animation != null)
                {
                    text.AppendLine("| `" + animation.Name + "` | " + Float(animation.Duration) + " |");
                }
            }

            text.AppendLine();
            text.AppendLine("## Skins (" + data.Skins.Count + ")");
            text.AppendLine();
            text.AppendLine("| Skin | Attachments | Part group |");
            text.AppendLine("| --- | --- | --- |");
            for (int i = 0; i < data.Skins.Count; i++)
            {
                Skin skin = data.Skins.Items[i];
                if (skin == null)
                {
                    continue;
                }

                int attachments = 0;
                foreach (Skin.SkinEntry entry in skin.GetAttachments())
                {
                    if (entry.Attachment != null)
                    {
                        attachments++;
                    }
                }

                text.AppendLine("| `" + skin.Name + "` | " + attachments + " | " +
                    SpineActorBase.SkinPartKey(skin.Name) + " |");
            }

            text.AppendLine();
            text.AppendLine("## Atlas pages and materials");
            text.AppendLine();
            if (asset.atlasAssets == null || asset.atlasAssets.Length == 0)
            {
                text.AppendLine("- (none)");
            }
            else
            {
                for (int i = 0; i < asset.atlasAssets.Length; i++)
                {
                    var atlas = asset.atlasAssets[i];
                    if (atlas == null)
                    {
                        continue;
                    }

                    text.AppendLine("### " + atlas.name);
                    text.AppendLine();
                    var pages = AtlasPageNames(atlas);
                    if (pages.Count == 0)
                    {
                        text.AppendLine("- pages: (could not read the atlas text)");
                    }
                    else
                    {
                        for (int p = 0; p < pages.Count; p++)
                        {
                            text.AppendLine("- page: `" + pages[p] + "`");
                        }
                    }

                    if (atlas.Materials != null)
                    {
                        foreach (Material material in atlas.Materials)
                        {
                            if (material == null)
                            {
                                continue;
                            }

                            text.AppendLine("- material: `" + material.name + "` — shader `" +
                                (material.shader != null ? material.shader.name : "(none)") + "`" +
                                ", texture `" + (material.mainTexture != null ? material.mainTexture.name : "(none)") + "`");
                        }
                    }

                    text.AppendLine();
                }
            }

            return text.ToString();
        }

        /// <summary>Page names of an atlas, read from the parsed atlas rather than its text.</summary>
        private static List<string> AtlasPageNames(AtlasAssetBase atlas)
        {
            var pages = new List<string>();
            Atlas parsed = atlas.GetAtlas();
            if (parsed == null)
            {
                return pages;
            }

            for (int i = 0; i < parsed.Pages.Count; i++)
            {
                AtlasPage page = parsed.Pages[i];
                if (page != null)
                {
                    pages.Add(page.name);
                }
            }

            return pages;
        }

        private static string InstalledRuntimeVersion()
        {
            string path = Path.GetFullPath(Path.Combine(Application.dataPath, "..", SpineRuntimePackageJson));
            if (!File.Exists(path))
            {
                return "(package.json not found)";
            }

            string json = File.ReadAllText(path);
            int nameIndex = json.IndexOf("\"version\"", StringComparison.Ordinal);
            if (nameIndex < 0)
            {
                return "(no version in package.json)";
            }

            int colon = json.IndexOf(':', nameIndex);
            int open = json.IndexOf('"', colon + 1);
            int close = open >= 0 ? json.IndexOf('"', open + 1) : -1;
            return open >= 0 && close > open ? json.Substring(open + 1, close - open - 1) : "(unreadable version)";
        }

        private static string AssetPath(SkeletonDataAsset asset)
        {
            string path = AssetDatabase.GetAssetPath(asset);
            return string.IsNullOrEmpty(path) ? asset.name : path;
        }

        private static string Float(float value)
        {
            return value.ToString("0.####", CultureInfo.InvariantCulture);
        }
    }
}
