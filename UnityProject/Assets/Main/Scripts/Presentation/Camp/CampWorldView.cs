        private void Build()
        {
            if (Built)
            {
                return;
            }

            Built = true;
            _art = new CampPlaceholderArt();

            Vector3 facing = _cameraEuler;

            // Ground first: it is the furthest thing on the plane, so everything else draws over it.
            // It is drawn opaque (one camp-only material, queue 2000) so the yard's decals, fake
            // shadows and light pools — the arena's queues, authored for an opaque floor — land on
            // top of it instead of behind it.
            SpriteRenderer ground = Place(
                "Ground", _art.Ground, At(0f, 0f, 0f), Quaternion.Euler(90f, 0f, 0f), 20f, 16f,
                CampSorting.GroundOrder);
            if (_groundMaterial != null)
            {
                ground.sharedMaterial = _groundMaterial;
            }

            // The stall and its keeper sit behind the shelf row, out of the walking area.
            Place("Stall", _art.Stall, At(-7.4f, 0.55f, 4.6f), Quaternion.Euler(facing), 1f, 1f, 10);
            Place("Grandmother", _art.Grandmother, At(-8.6f, 1.05f, 4.1f), Quaternion.Euler(facing), 1.7f, 1.7f, 12);

            // The incense pot stays as the altar's counterpart in the world: the drop zone itself is
            // on the จัดย่าม screen, but the pot the player gives a piece back to belongs in the sala.
            _pot = Place("AltarPot", _art.Pot, At(7.6f, 0.5f, 2.2f), Quaternion.Euler(78f, 0f, 0f), 1.3f, 1.3f, 13);

            // ยายจันทร์'s own sign, above her stall: her name and what she is selling (localized,
            // from the presenter like every other string here).
            _stallLabel = CreateLabel(
                "StallLabel", At(-7.4f, 2.7f, 4.6f), Quaternion.Euler(_cameraEuler), 1.6f,
                new Color(0.94f, 0.88f, 0.66f, 1f), new Vector2(6.4f, 1.4f), 17);

            for (int i = 0; i < 4; i++)
            {
                _stations.Add(BuildStation(i));
            }

            // The player, in front of the furniture: the walk bounds keep it there, so its sorting
            // order can be a constant instead of a per-frame depth sort.
            _player = Place("Player", _art.Player, _spawn, Quaternion.Euler(facing), 1.5f, 1.5f, CampSorting.PlayerOrder);
            BuildPlayerFigure(_player.gameObject);

            BuildResetDrum(facing);

            ApplyCamera();
        }

        private Station BuildStation(int index)
        {
            float x = (index - 1.5f) * _shelfSpacing;
            var anchor = new Vector3(x, 0f, _shelfZ);

            var station = new Station
            {
                Anchor = anchor,
                Rack = Place(
                    "Shelf" + index, _art.Shelf, new Vector3(x, _rackHeight, _shelfZ),
                    Quaternion.Euler(_cameraEuler), 1f, 1f, 14),
                Board = Place(
                    "ShelfBoard" + index, _art.Sign, new Vector3(x, _signHeight, _shelfZ + 0.02f),
                    Quaternion.Euler(_cameraEuler), _signScale, _signScale, 15),
                Plate = Place(
                    "ShelfItem" + index, _art.ShelfItem, new Vector3(x, _rackHeight + 0.16f, _shelfZ - 0.12f),
                    Quaternion.Euler(_cameraEuler), 0.5f, 0.5f, 16),
            };

            station.RackColour = _idleRack;
            station.Rack.color = _idleRack;

            // The board is the price's own background, so it is also half of the label's contrast:
            // a light cream board lets a near-black ink clear WCAG AA at the type size below.
            station.Board.color = BoardTint;

            // 3.8 rather than 1.9: at 1080p one world unit is 81.8 px, and the price's ink has to be
            // at least CampTheme.LabelFloorPixels (22) tall. 1.9 measured 12 px, so the type is
            // scaled by 22/12 and then a little, to clear the floor rather than touch it. The label
            // sits high on the board so the focused store's sentence has room below the price.
            station.Price = CreateLabel(
                "ShelfPrice" + index, new Vector3(x, _signHeight + 0.7f, _shelfZ - 0.4f),
                Quaternion.Euler(_cameraEuler), PriceFontSize, PriceInk,
                new Vector2(_shelfSpacing * 0.86f, 1.3f), 17);

            // 09c work item 4 wants ล็อกสินค้าก่อนรีเซ็ต reachable from the shelf's own sign, so the
            // lock is the board's first row under the price: it is a control the player taps, drawn
            // a step below the price and above the focused store's caption. It is deliberately not
            // at the board's bottom edge — that row is the station's own click centre, and the lock
            // is tested before the station, so a click meant for the shelf would pin it.
            station.Lock = CreateLabel(
                "ShelfLock" + index, new Vector3(x, _signHeight + 0.02f, _shelfZ - 0.42f),
                Quaternion.Euler(_cameraEuler), LockFontSize, PriceInk,
                new Vector2(_shelfSpacing * 0.7f, 0.7f), 18);

            // The focused store's sentence has its own label in the board's lower band: folded into
            // the price label it made that label's ink one tall run with the price's, and the board's
            // ink height is the number the readability gate reads.
            station.Detail = CreateLabel(
                "ShelfDetail" + index, new Vector3(x, _signHeight - 0.45f, _shelfZ - 0.42f),
                Quaternion.Euler(_cameraEuler), DetailFontSize, PriceInk,
                new Vector2(_shelfSpacing * 0.92f, 0.6f), 17);

            return station;
        }

        /// <summary>
        /// Puts the doctor's <see cref="SpinePlayerView"/> on the transform the walker moves, so the
        /// figure is where the player is by construction: one transform, one owner of the walking.
        /// </summary>
        /// <remarks>
        /// The anchor already carries the camera's own tilt (every standing sprite in the sala does),
        /// which is the pitch the arena's figure is posed at too — the actor inherits it, so nothing
        /// re-derives an orientation here. The draw order is the sala's authored player row
        /// (<see cref="CampSorting.PlayerOrder"/>), a constant because the walk bounds keep the
        /// player in front of the furniture.
        /// </remarks>
        private void BuildPlayerFigure(GameObject anchor)
        {
            if (anchor == null)
            {
                return;
            }

            SpinePlayerView spineFigure = anchor.AddComponent<SpinePlayerView>();
            spineFigure.Configure(_spineProfile);
            spineFigure.SetSortingOrder(CampSorting.PlayerOrder);

            _figureHost = spineFigure;
            _figure = spineFigure.GetComponent<IPlayerFigure>();
        }

        /// <summary>
        /// Builds the figure, once. Returns false (leaving the placeholder silhouette drawing the
        /// player) when the scene carries no profile or the skeleton would not draw; the view itself
        /// logged the <c>noun.problem</c> code, and a release build says once that the silhouette is
        /// what the player is looking at.
        /// </summary>
        public bool BeginPlayerFigure()
        {
            if (_figure == null)
            {
                return false;
            }

            if (_figure.IsBegun)
            {
                return true;
            }

            if (!_figure.Begin())
            {
                if (!DevelopmentBuild && _player != null)
                {
                    Debug.LogWarning(
                        "[CampWorldView] " + (_figure.ErrorCode ?? "spine.player_unknown") +
                        ": the player figure could not be built, so the placeholder silhouette draws " +
                        "the doctor in the sala.", _figureHost);
                }

                return false;
            }

            // One doctor, not two: the silhouette was only ever the stand-in.
            if (_player != null)
            {
                _player.enabled = false;
            }

            return true;
        }

        /// <summary>True in the Editor and in a development build — the two places a loud log is cheap.</summary>
        private static bool DevelopmentBuild => Debug.isDebugBuild || Application.isEditor;

        private void BuildResetDrum(Vector3 facing)
        {
            _drum = Place("ResetDrum", _art.Drum, _resetPosition, Quaternion.Euler(facing), 1.6f, 1.6f, 14);

            _resetLabel = CreateLabel(
                "ResetLabel", _resetPosition + new Vector3(0f, 1.25f, -0.2f),
                Quaternion.Euler(_cameraEuler), 1.5f, new Color(0.94f, 0.88f, 0.66f, 1f),
                new Vector2(3.4f, 0.8f), 17);
        }

        private TextMeshPro CreateLabel(
            string name, Vector3 position, Quaternion rotation, float size, Color colour,
            Vector2 rect, int sortingOrder)
        {
            var gameObject = new GameObject(name);
            gameObject.transform.SetParent(transform, false);
            gameObject.transform.position = position;
            gameObject.transform.rotation = rotation;

            var label = gameObject.AddComponent<TextMeshPro>();
            label.text = string.Empty;
            label.alignment = TextAlignmentOptions.Center;
            label.fontSize = size;
            label.color = colour;
            label.rectTransform.sizeDelta = rect;

            // The labels are read, never clicked: a click belongs to the station they sit on.
            label.raycastTarget = false;

            if (_font != null)
            {
                label.font = _font;
            }

            MeshRenderer renderer = gameObject.GetComponent<MeshRenderer>();
            if (renderer != null)
            {
                renderer.sortingOrder = sortingOrder;
            }

            return label;
        }

        private Vector3 At(float x, float y, float z) => new Vector3(x, y, z);

        private SpriteRenderer Place(
            string name, Sprite sprite, Vector3 position, Quaternion rotation,
            float scaleX, float scaleY, int sortingOrder)
        {
            var gameObject = new GameObject(name);
            gameObject.transform.SetParent(transform, false);
            gameObject.transform.position = position;
            gameObject.transform.rotation = rotation;
            gameObject.transform.localScale = new Vector3(scaleX, scaleY, 1f);

            var renderer = gameObject.AddComponent<SpriteRenderer>();
            renderer.sprite = sprite;
            renderer.sortingOrder = sortingOrder;
            return renderer;
        }

