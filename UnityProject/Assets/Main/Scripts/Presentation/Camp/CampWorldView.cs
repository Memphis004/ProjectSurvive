        /// <summary>Resolves the screen's state and starts writing the stations. Idempotent.</summary>
        public void Bind()
        {
            if (_bound)
            {
                return;
            }

            if (_scope == null || _scope.Container == null)
            {
                Debug.LogError("CampWorldView needs a built scope to resolve the camp state.", this);
                return;
            }

            // Stage 17c: the figure is built once, here — the camp's start is the one place the
            // scene knows it is entering, and a figure built later would pop in mid-walk.
            BeginPlayerFigure();

            _bound = true;
            _state = _scope.Container.Resolve<CampUiState>();
            _subscriptions.Add(_state.Shop.Subscribe(RenderStations));
            _subscriptions.Add(_state.FocusedShelfDetail.Subscribe(SetFocusedDetail));
            _subscriptions.Add(_state.RefreshButtonLabel.Subscribe(SetResetLabel));
            _subscriptions.Add(_state.NpcName.Subscribe(_ => RenderStall()));
            _subscriptions.Add(_state.ShopCaption.Subscribe(_ => RenderStall()));
        }

        private void OnDestroy()
        {
            for (int i = 0; i < _subscriptions.Count; i++)
            {
                _subscriptions[i].Dispose();
            }

            _subscriptions.Clear();
            _state = null;
            _bound = false;

            _art?.Dispose();
            _art = null;
        }

