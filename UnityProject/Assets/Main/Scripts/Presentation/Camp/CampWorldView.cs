        /// <summary>
        /// Frames the sala: a tilted orthographic camera, kept on the player but inside a box, so
        /// walking moves the world under a camera that never loses the stall.
        /// </summary>
        private void ApplyCamera()
        {
            if (_camera == null)
            {
                return;
            }

            _camera.orthographic = true;
            _camera.orthographicSize = _cameraSize;
            _camera.transform.rotation = Quaternion.Euler(_cameraEuler);

            Vector3 player = PlayerPosition;
            Vector3 position = new Vector3(player.x, 0f, player.z) + _cameraOffset;
            position.x = Mathf.Clamp(position.x, _cameraXLimit.x, _cameraXLimit.y);
            position.z = Mathf.Clamp(position.z, _cameraZLimit.x, _cameraZLimit.y);
            _camera.transform.position = position;
        }

