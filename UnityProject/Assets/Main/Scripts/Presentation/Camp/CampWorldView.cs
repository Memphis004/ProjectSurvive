    /// <summary>
    /// ศาลาพัก as the player walks it: the packed-earth ground, ยายจันทร์'s stall, the player's
    /// figure, one <b>shelf station</b> per shop slot (its piece, its price and its lock control,
    /// all in world space) and the เซียมซี cylinder the chest's re-roll is cast from.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Stage 09c moved the stall out of the UI. There is <b>one</b> shop list and it is this one —
    /// four stations standing in the sala (\"ไม่มีรายการร้านใน UI ซ้ำอีกชุด\") — so the panel that used
    /// to draw a second list is gone. The labels are still written from
    /// <see cref="CampUiState.Shop"/>, i.e. from the strings <see cref="CampPresenter"/> already
    /// composed: this view formats nothing and prices nothing (AGENTS rule 10).
    /// </para>
    /// <para>
    /// It owns the framing and nothing else that moves. <see cref="CampPlayerView"/> walks the
    /// player and decides what a button does; this view answers \"where is shelf 3 on screen\" for
    /// the click test, for the report and for the focus highlight, which is the same question the
    /// browser test asks (AGENTS rule 12: one answer, not two).
    /// </para>
    /// <para>
    /// Art is generated by <see cref="CampPlaceholderArt"/> and released in <c>OnDestroy</c>
    /// (AGENTS rule 13).
    /// </para>
    /// </remarks>
    [DisallowMultipleComponent]
    public sealed class CampWorldView : MonoBehaviour
    {
        /// <summary>One shelf station's geometry, built once in <c>Awake</c>.</summary>
        private sealed class Station
        {
            public SpriteRenderer Rack;
            public SpriteRenderer Board;
            public SpriteRenderer Plate;
            public TextMeshPro Price;
            public TextMeshPro Lock;
            public Vector3 Anchor;
            public Color RackColour;
        }

        [SerializeField] private LifetimeScope _scope;

        [Tooltip("The scene's camera. Framed here; the player walks under it.")]
        [SerializeField] private Camera _camera;

        [SerializeField] private TMP_FontAsset _font;

        [Header("Framing (authored by ProjectSetup)")]
        [SerializeField] private Vector3 _cameraOffset = new Vector3(0f, 7.2f, -10.5f);
        [SerializeField] private Vector3 _cameraEuler = new Vector3(32f, 0f, 0f);
        [SerializeField] private float _cameraSize = 6.6f;

        [Tooltip("Where the follow camera is allowed to sit, so the sala stays framed.")]
        [SerializeField] private Vector2 _cameraXLimit = new Vector2(-4f, 4f);
        [SerializeField] private Vector2 _cameraZLimit = new Vector2(-13f, -8f);

        [Header("Placement (world XZ, +Z away from the camera)")]
        [SerializeField] private float _shelfZ = 3.4f;
        [SerializeField] private float _shelfSpacing = 3f;
        [SerializeField] private float _rackHeight = 0.75f;
        [SerializeField] private float _signHeight = 2.6f;
        [SerializeField] private float _signScale = 0.85f;
        [SerializeField] private Vector3 _resetPosition = new Vector3(-7.2f, 0.7f, 0.4f);
        [SerializeField] private Vector3 _spawn = new Vector3(0f, 0.8f, -2.2f);

        [Tooltip("The area the player may walk in (XZ). In front of the shelf row, so the player never stands inside the furniture.")]
        [SerializeField] private Vector2 _walkXLimit = new Vector2(-8.4f, 8.4f);
        [SerializeField] private Vector2 _walkZLimit = new Vector2(-3.6f, 2.6f);

        [Header("Focus")]
        [SerializeField] private Color _idleRack = new Color(0.86f, 0.80f, 0.68f, 1f);
        [SerializeField] private Color _focusedRack = new Color(1f, 0.93f, 0.66f, 1f);

        private readonly List<IDisposable> _subscriptions = new List<IDisposable>(2);
        private readonly List<Station> _stations = new List<Station>(4);

        private CampPlaceholderArt _art;
        private CampUiState _state;
        private SpriteRenderer _player;
        private SpriteRenderer _drum;
        private SpriteRenderer _pot;
        private TextMeshPro _resetLabel;
        private TextMeshPro _stallLabel;
        private bool _bound;
        private int _focusedShelf = -1;
        private bool _resetFocused;

        /// <summary>How many shelf stations stand in the sala (a test reads this).</summary>
        public int ShelfCount => _stations.Count;

        /// <summary>True once the sala has been built.</summary>
        public bool Built { get; private set; }

        /// <summary>The player's transform. <see cref="CampPlayerView"/> is what moves it.</summary>
        public Transform PlayerTransform => _player == null ? null : _player.transform;

        /// <summary>Where the player is now (world space).</summary>
        public Vector3 PlayerPosition => _player == null ? _spawn : _player.transform.position;

        /// <summary>Where the เซียมซี cylinder stands.</summary>
        public Vector3 ResetPosition => _resetPosition;

        /// <summary>The framing camera.</summary>
        public Camera Camera => _camera;

        /// <summary>Where the camera is now, which the layout report keys on.</summary>
        public Vector3 CameraPosition => _camera == null ? Vector3.zero : _camera.transform.position;

        /// <summary>Where the player starts walking from.</summary>
        public Vector3 SpawnPosition => _spawn;

        /// <summary>How many price boards exist (the Stage 09 name for the shelf count).</summary>
        public int PriceBoardCount => _stations.Count;

        private void Awake()
        {
            Build();
        }

        /// <summary>Resolves the screen's state and starts writing the stations. Idempotent.</summary>
        public void Bind()
        {
            if (_bound)
            {
                return;
            }

            if (_scope == null || _scope.Container == null)
            {
                Debug.LogError("CampWorldView needs a built scope to resolve the camp state.", this);
                return;
            }

            _bound = true;
            _state = _scope.Container.Resolve<CampUiState>();
            _subscriptions.Add(_state.Shop.Subscribe(RenderStations));
            _subscriptions.Add(_state.RefreshButtonLabel.Subscribe(SetResetLabel));
            _subscriptions.Add(_state.NpcName.Subscribe(_ => RenderStall()));
            _subscriptions.Add(_state.ShopCaption.Subscribe(_ => RenderStall()));
        }

        private void OnDestroy()
        {
            for (int i = 0; i < _subscriptions.Count; i++)
            {
                _subscriptions[i].Dispose();
            }

            _subscriptions.Clear();
            _state = null;
            _bound = false;

            _art?.Dispose();
            _art = null;
        }

        /// <summary>
        /// Keeps the camera on the player. Late, so it reads the position the player ended the frame
        /// at rather than the one it started at.
        /// </summary>
        private void LateUpdate() => ApplyCamera();

        // ------------------------------------------------------------------
        // the sala
        // ------------------------------------------------------------------

        private void Build()
        {
            if (Built)
            {
                return;
            }

            Built = true;
            _art = new CampPlaceholderArt();

            Vector3 facing = _cameraEuler;

            // Ground first: it is the furthest thing on the plane, so everything else draws over it.
            Place("Ground", _art.Ground, At(0f, 0f, 0f), Quaternion.Euler(90f, 0f, 0f), 20f, 16f, 1);

            // The stall and its keeper sit behind the shelf row, out of the walking area.
            Place("Stall", _art.Stall, At(-7.4f, 0.55f, 4.6f), Quaternion.Euler(facing), 1f, 1f, 10);
            Place("Grandmother", _art.Grandmother, At(-8.6f, 1.05f, 4.1f), Quaternion.Euler(facing), 1.7f, 1.7f, 12);

            // The incense pot stays as the altar's counterpart in the world: the drop zone itself is
            // on the จัดย่าม screen, but the pot the player gives a piece back to belongs in the sala.
            _pot = Place("AltarPot", _art.Pot, At(7.6f, 0.5f, 2.2f), Quaternion.Euler(78f, 0f, 0f), 1.3f, 1.3f, 13);

            // ยายจันทร์'s own sign, above her stall: her name and what she is selling (localized,
            // from the presenter like every other string here).
            _stallLabel = CreateLabel(
                "StallLabel", At(-7.4f, 2.7f, 4.6f), Quaternion.Euler(_cameraEuler), 1.6f,
                new Color(0.94f, 0.88f, 0.66f, 1f), new Vector2(6.4f, 1.4f), 17);

            for (int i = 0; i < 4; i++)
            {
                _stations.Add(BuildStation(i));
            }

            // The player, in front of the furniture: the walk bounds keep it there, so its sorting
            // order can be a constant instead of a per-frame depth sort.
            _player = Place("Player", _art.Player, _spawn, Quaternion.Euler(facing), 1.5f, 1.5f, 18);

            BuildResetDrum(facing);

            ApplyCamera();
        }

        private Station BuildStation(int index)
        {
            float x = (index - 1.5f) * _shelfSpacing;
            var anchor = new Vector3(x, 0f, _shelfZ);

            var station = new Station
            {
                Anchor = anchor,
                Rack = Place(
                    "Shelf" + index, _art.Shelf, new Vector3(x, _rackHeight, _shelfZ),
                    Quaternion.Euler(_cameraEuler), 1f, 1f, 14),
                Board = Place(
                    "ShelfBoard" + index, _art.Sign, new Vector3(x, _signHeight, _shelfZ + 0.02f),
                    Quaternion.Euler(_cameraEuler), _signScale, _signScale, 15),
                Plate = Place(
                    "ShelfItem" + index, _art.ShelfItem, new Vector3(x, _rackHeight + 0.16f, _shelfZ - 0.12f),
                    Quaternion.Euler(_cameraEuler), 0.5f, 0.5f, 16),
            };

            station.RackColour = _idleRack;
            station.Rack.color = _idleRack;
            station.Board.color = Color.white;

            station.Price = CreateLabel(
                "ShelfPrice" + index, new Vector3(x, _signHeight - 0.05f, _shelfZ - 0.4f),
                Quaternion.Euler(_cameraEuler), 1.9f, new Color(0.10f, 0.08f, 0.08f, 1f),
                new Vector2(_shelfSpacing * 0.86f, 1.7f), 17);

            // The lock control is its own label, drawn under the price: 09c work item 4 wants
            // ล็อกสินค้าก่อนรีเซ็ต reachable from the shelf's own sign.
            station.Lock = CreateLabel(
                "ShelfLock" + index, new Vector3(x, _signHeight - 0.62f, _shelfZ - 0.42f),
                Quaternion.Euler(_cameraEuler), 1.35f, new Color(0.32f, 0.16f, 0.10f, 1f),
                new Vector2(_shelfSpacing * 0.7f, 0.6f), 18);

            return station;
        }

        private void BuildResetDrum(Vector3 facing)
        {
            _drum = Place("ResetDrum", _art.Drum, _resetPosition, Quaternion.Euler(facing), 1.6f, 1.6f, 14);

            _resetLabel = CreateLabel(
                "ResetLabel", _resetPosition + new Vector3(0f, 1.25f, -0.2f),
                Quaternion.Euler(_cameraEuler), 1.5f, new Color(0.94f, 0.88f, 0.66f, 1f),
                new Vector2(3.4f, 0.8f), 17);
        }

        private TextMeshPro CreateLabel(
            string name, Vector3 position, Quaternion rotation, float size, Color colour,
            Vector2 rect, int sortingOrder)
        {
            var gameObject = new GameObject(name);
            gameObject.transform.SetParent(transform, false);
            gameObject.transform.position = position;
            gameObject.transform.rotation = rotation;

            var label = gameObject.AddComponent<TextMeshPro>();
            label.text = string.Empty;
            label.alignment = TextAlignmentOptions.Center;
            label.fontSize = size;
            label.color = colour;
            label.rectTransform.sizeDelta = rect;

            // The labels are read, never clicked: a click belongs to the station they sit on.
            label.raycastTarget = false;

            if (_font != null)
            {
                label.font = _font;
            }

            MeshRenderer renderer = gameObject.GetComponent<MeshRenderer>();
            if (renderer != null)
            {
                renderer.sortingOrder = sortingOrder;
            }

            return label;
        }

        private Vector3 At(float x, float y, float z) => new Vector3(x, y, z);

        private SpriteRenderer Place(
            string name, Sprite sprite, Vector3 position, Quaternion rotation,
            float scaleX, float scaleY, int sortingOrder)
        {
            var gameObject = new GameObject(name);
            gameObject.transform.SetParent(transform, false);
            gameObject.transform.position = position;
            gameObject.transform.rotation = rotation;
            gameObject.transform.localScale = new Vector3(scaleX, scaleY, 1f);

            var renderer = gameObject.AddComponent<SpriteRenderer>();
            renderer.sprite = sprite;
            renderer.sortingOrder = sortingOrder;
            return renderer;
        }

        // ------------------------------------------------------------------
        // the follow camera
        // ------------------------------------------------------------------

        /// <summary>
        /// Frames the sala: a tilted orthographic camera, kept on the player but inside a box, so
        /// walking moves the world under a camera that never loses the stall.
        /// </summary>
        private void ApplyCamera()
        {
            if (_camera == null)
            {
                return;
            }

            _camera.orthographic = true;
            _camera.orthographicSize = _cameraSize;
            _camera.transform.rotation = Quaternion.Euler(_cameraEuler);

            Vector3 player = PlayerPosition;
            Vector3 position = new Vector3(player.x, 0f, player.z) + _cameraOffset;
            position.x = Mathf.Clamp(position.x, _cameraXLimit.x, _cameraXLimit.y);
            position.z = Mathf.Clamp(position.z, _cameraZLimit.x, _cameraZLimit.y);
            _camera.transform.position = position;
        }

        // ------------------------------------------------------------------
        // what the player view, the report and the tests ask
        // ------------------------------------------------------------------

        /// <summary>Where a shelf station stands (its base, which is what walking distance uses).</summary>
        public Vector3 ShelfPosition(int index) =>
            index >= 0 && index < _stations.Count ? _stations[index].Anchor : Vector3.zero;

        /// <summary>The walking area, clamped per axis.</summary>
        public Vector3 ClampToWalkArea(Vector3 position)
        {
            position.x = Mathf.Clamp(position.x, _walkXLimit.x, _walkXLimit.y);
            position.z = Mathf.Clamp(position.z, _walkZLimit.x, _walkZLimit.y);
            position.y = _spawn.y;
            return position;
        }

        /// <summary>
        /// Where the player may walk, as a rectangle in world XZ: <c>x</c> is world X and <c>y</c> is
        /// world Z, so <c>yMin</c> is the near edge (towards the camera) and <c>yMax</c> the far one.
        /// Normalised on purpose — <c>Rect.MinMaxRect</c> with the Z limits in the other order would
        /// hand back a rectangle with a negative height and quietly make <c>yMin</c> the far edge.
        /// </summary>
        public Rect WalkArea => Rect.MinMaxRect(_walkXLimit.x, _walkZLimit.x, _walkXLimit.y, _walkZLimit.y);

        /// <summary>The station a click at <paramref name="screenPoint"/> lands on, or -1.</summary>
        /// <remarks>
        /// Screen-space rather than a physics raycast: the sala has no colliders (nothing in the
        /// camp is simulated), and this is the same rectangle the report publishes, so a browser
        /// test that clicks a station and this method agree by construction.
        /// </remarks>
        public int ShelfAtScreenPoint(Vector2 screenPoint, out bool onTheLock)
        {
            onTheLock = false;

            for (int i = 0; i < _stations.Count; i++)
            {
                if (TryGetShelfLockScreenRect(i, out Rect lockRect) && lockRect.Contains(screenPoint))
                {
                    onTheLock = true;
                    return i;
                }
            }

            for (int i = 0; i < _stations.Count; i++)
            {
                if (TryGetShelfScreenRect(i, out Rect rect) && rect.Contains(screenPoint))
                {
                    return i;
                }
            }

            return -1;
        }

        /// <summary>True when a click at <paramref name="screenPoint"/> lands on the เซียมซี cylinder.</summary>
        public bool IsResetAtScreenPoint(Vector2 screenPoint) =>
            TryGetResetScreenRect(out Rect rect) && rect.Contains(screenPoint);

        /// <summary>The whole station: rack plus board, which is one click target.</summary>
        public bool TryGetShelfScreenRect(int index, out Rect rect)
        {
            rect = default;

            if (index < 0 || index >= _stations.Count)
            {
                return false;
            }

            Station station = _stations[index];
            bool found = TryProject(station.Rack, out rect);

            if (TryProject(station.Board, out Rect board))
            {
                rect = found ? Union(rect, board) : board;
                found = true;
            }

            return found;
        }

        /// <summary>
        /// The station's lock control on its own, so a click can mean ล็อกไว้.
        /// </summary>
        /// <remarks>
        /// The <b>drawn</b> rectangle of the label — the glyphs a player aims at — rather than its
        /// layout box. The box the label was authored in (2.1 × 0.6 world units) reaches up over the
        /// station's own centre, so publishing it as the lock's target would make a click meant for
        /// the shelf lock it instead. 
        /// </remarks>
        public bool TryGetShelfLockScreenRect(int index, out Rect rect)
        {
            rect = default;
            return index >= 0 && index < _stations.Count && TryProject(_stations[index].Lock.renderer, out rect);
        }

        /// <summary>Where the เซียมซี cylinder is on screen.</summary>
        public bool TryGetResetScreenRect(out Rect rect)
        {
            rect = default;
            return TryProject(_drum, out rect);
        }

        /// <summary>Where the player is on screen, which a test uses to prove it moved.</summary>
        public bool TryGetPlayerScreenRect(out Rect rect) => TryProject(_player, out rect);

        /// <summary>Highlights the station the player is standing at (-1 for none).</summary>
        public void SetFocusedShelf(int index)
        {
            if (_focusedShelf == index)
            {
                return;
            }

            _focusedShelf = index;

            for (int i = 0; i < _stations.Count; i++)
            {
                _stations[i].Rack.color = i == index ? _focusedRack : _idleRack;
                _stations[i].Plate.color = i == index ? Color.white : new Color(1f, 1f, 1f, 0.72f);
            }
        }

        /// <summary>Highlights the เซียมซี cylinder while the player stands at it.</summary>
        public void SetResetFocused(bool focused)
        {
            if (_resetFocused == focused || _drum == null)
            {
                return;
            }

            _resetFocused = focused;
            _drum.color = focused ? _focusedRack : Color.white;
        }

        /// <summary>Which station is highlighted, or -1.</summary>
        public int FocusedShelf => _focusedShelf;

        /// <summary>True while the เซียมซี cylinder is highlighted.</summary>
        public bool ResetFocused => _resetFocused;

        private bool TryProject(Renderer renderer, out Rect rect)
        {
            rect = default;

            if (renderer == null || _camera == null)
            {
                return false;
            }

            return TryProject(renderer.bounds, out rect);
        }

        /// <summary>
        /// Projects a world box to a screen rectangle, in pixels with the origin at the
        /// <b>bottom-left</b> — the convention Unity reports and the one <see cref="CampReport"/>
        /// publishes.
        /// </summary>
        private bool TryProject(Bounds bounds, out Rect rect)
        {
            rect = default;

            if (_camera == null)
            {
                return false;
            }

            Vector3 min = bounds.min;
            Vector3 max = bounds.max;
            float xMin = float.MaxValue;
            float yMin = float.MaxValue;
            float xMax = float.MinValue;
            float yMax = float.MinValue;

            for (int corner = 0; corner < 8; corner++)
            {
                var point = new Vector3(
                    (corner & 1) == 0 ? min.x : max.x,
                    (corner & 2) == 0 ? min.y : max.y,
                    (corner & 4) == 0 ? min.z : max.z);

                Vector3 screen = _camera.WorldToScreenPoint(point);
                if (screen.z <= 0f)
                {
                    // Behind the camera: the box has no on-screen rectangle to speak of, and half
                    // of one would be a lie.
                    return false;
                }

                xMin = Mathf.Min(xMin, screen.x);
                yMin = Mathf.Min(yMin, screen.y);
                xMax = Mathf.Max(xMax, screen.x);
                yMax = Mathf.Max(yMax, screen.y);
            }

            rect = Rect.MinMaxRect(xMin, yMin, xMax, yMax);
            return true;
        }

        private static Rect Union(Rect a, Rect b) => Rect.MinMaxRect(
            Mathf.Min(a.xMin, b.xMin),
            Mathf.Min(a.yMin, b.yMin),
            Mathf.Max(a.xMax, b.xMax),
            Mathf.Max(a.yMax, b.yMax));

        // ------------------------------------------------------------------
        // labels
        // ------------------------------------------------------------------

        /// <summary>
        /// Writes one station's own words: the piece it offers with its price, or that it is empty
        /// or already rented, plus the lock control's current meaning.
        /// </summary>
        /// <remarks>
        /// Every string comes from the presenter through <see cref="CampUiState"/>. A station that
        /// composed \"10 เบี้ย\" here would be the second price rule the stage forbids.
        /// </remarks>
        private void RenderStations(CampShopSlotModel[] slots)
        {
            for (int i = 0; i < _stations.Count; i++)
            {
                Station station = _stations[i];

                if (slots == null || i >= slots.Length || slots[i].IsEmpty)
                {
                    station.Price.text = _state == null ? string.Empty : _state.EmptySlotLabel.Value;
                    station.Lock.text = string.Empty;
                    station.Plate.enabled = false;
                    continue;
                }

                CampShopSlotModel slot = slots[i];
                station.Plate.enabled = !slot.IsPurchased;

                station.Price.text = slot.IsPurchased
                    ? slot.Name + "\n" + Label(_state == null ? null : _state.RentedLabel)
                    : slot.Name + "\n" + slot.PriceLabel;

                station.Lock.text = slot.IsLocked
                    ? Label(_state == null ? null : _state.UnpinLabel)
                    : Label(_state == null ? null : _state.PinLabel);

                // Build the glyph mesh now rather than at the end of the frame. This text is a click
                // target the layout report publishes, and a TextMeshPro has no bounds — so its
                // rectangle measures as a zero-area point and cannot be hit — until it has rebuilt.
                // Without this, the report describes a one-pixel lock for a frame after the camp
                // starts, which is exactly the frame a browser test reads.
                station.Lock.ForceMeshUpdate();
            }
        }

        private void SetResetLabel(string label)
        {
            if (_resetLabel != null)
            {
                _resetLabel.text = label ?? string.Empty;
            }
        }

        /// <summary>The stall's two lines: whose it is, and what it is.</summary>
        private void RenderStall()
        {
            if (_stallLabel != null && _state != null)
            {
                _stallLabel.text = Label(_state.NpcName) + "\n" + Label(_state.ShopCaption);
            }
        }

        private static string Label(ReactiveProperty<string> property) =>
            property == null ? string.Empty : property.Value;
    }
}
