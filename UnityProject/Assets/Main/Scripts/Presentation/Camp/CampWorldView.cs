        /// <summary>
        /// Writes one station's own words: the piece it offers with its price, or that it is empty
        /// or already rented, plus the lock control's current meaning.
        /// </summary>
        /// <remarks>
        /// Every string comes from the presenter through <see cref="CampUiState"/>. A station that
        /// composed \"10 เบี้ย\" here would be the second price rule the stage forbids.
        /// </remarks>
        private void RenderStations(CampShopSlotModel[] slots)
        {
            _slots = slots;

            for (int i = 0; i < _stations.Count; i++)
            {
                Station station = _stations[i];

                if (slots == null || i >= slots.Length || slots[i].IsEmpty)
                {
                    station.Price.text = _state == null ? string.Empty : _state.EmptySlotLabel.Value;
                    station.Lock.text = string.Empty;
                    station.Detail.text = string.Empty;
                    station.Plate.enabled = false;
                    continue;
                }

                CampShopSlotModel slot = slots[i];
                station.Plate.enabled = !slot.IsPurchased;

                // The number is the line the player came to read; the name identifies it one step
                // down, which is what leaves the board room for the focused store's sentence. The
                // name is a rich-text size tag rather than a second label, so both lines share one
                // label and the price's own ink height stays the taller of the two.
                string name = "<size=" + NameFontPercent + "%>" + slot.Name + "</size>";

                station.Price.text = name + "\n"
                    + (slot.IsPurchased
                        ? Label(_state == null ? null : _state.RentedLabel)
                        : slot.PriceLabel);

                // Stage 09n: the store the player stands at carries its detail on its own board, from
                // the same readout the pointer's tooltip uses. Only the focused station's caption
                // fills in.
                station.Detail.text = i == _focusedShelf ? _focusDetail : string.Empty;

                station.Lock.text = slot.IsLocked
                    ? Label(_state == null ? null : _state.UnpinLabel)
                    : Label(_state == null ? null : _state.PinLabel);

                // Build the glyph mesh now rather than at the end of the frame. This text is a click
                // target the layout report publishes, and a TextMeshPro has no bounds — so its
                // rectangle measures as a zero-area point and cannot be hit — until it has rebuilt.
                // Without this, the report describes a one-pixel lock for a frame after the camp
                // starts, which is exactly the frame a browser test reads.
                station.Lock.ForceMeshUpdate();
            }
        }

        /// <summary>
        /// Keeps the walk-up detail for the focused station and repaints the boards (Stage 09n).
        /// </summary>
        /// <remarks>
        /// The whole row is repainted rather than one label: a station that gained or lost the detail
        /// line must not keep a stale third row, and four labels is not a cost paid per frame.
        /// </remarks>
        private void SetFocusedDetail(string detail)
        {
            _focusDetail = detail ?? string.Empty;
            RenderStations(_slots);
        }

        private void SetResetLabel(string label)
        {
            if (_resetLabel != null)
            {
                _resetLabel.text = label ?? string.Empty;
            }
        }

        /// <summary>The stall's two lines: whose it is, and what it is.</summary>
        private void RenderStall()
        {
            if (_stallLabel != null && _state != null)
            {
                _stallLabel.text = Label(_state.NpcName) + "\n" + Label(_state.ShopCaption);
            }
        }

        private static string Label(ReactiveProperty<string> property) =>
            property == null ? string.Empty : property.Value;
    }
