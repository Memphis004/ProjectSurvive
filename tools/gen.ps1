<#
.SYNOPSIS
    Generate everything in lib/Runtime/Generated from data/ and proto/ (Stage 02).

.DESCRIPTION
    The single entry point of the static data pipeline. It works from ANY
    current directory: every path is resolved from the script's own location.

    Steps
      1. ensure the pinned toolchain is installed (tools/setup-tools.ps1)
      2. run Luban 5.1.0 with `--strict`:
           data/  -> lib/Runtime/Generated/Luban/*.cs        (Luban C# readers)
                  -> lib/Tests~/data/*.bytes                 (test tables)
                  -> UnityProject/Assets/Main/Resources/Config/*.bytes
      3. compute a deterministic config hash over the generated bytes and write
         it into lib/Runtime/Generated/Luban/ConfigBuildMetadata.g.cs
      4. run protoc 33.6:
           proto/app.proto -> lib/Runtime/Generated/Proto/App.cs (exactly one copy)

    Reproducibility: the tracked output (generated C#) contains no timestamp,
    absolute path or machine name, so running this twice from the same data/
    leaves `git diff` empty. lib/Tests~/data and Resources/Config hold .bytes,
    which ADR 0001 keeps out of Git; tools/verify-generated.ps1 checks those by
    regenerating into a temporary directory and comparing hashes.

    `--strict` matters: without it Luban treats a failing `#ref` / range
    validator as a warning and still exits 0.

.PARAMETER DataDir
    Source data directory. Default: <repo>/data

.PARAMETER OutDir
    Write every generated artifact under this directory instead of the real
    repository locations. Used by tools/validate-data.ps1 so that a deliberately
    broken fixture can be generated without touching the working tree.

.PARAMETER SkipBootstrap
    Do not try to install the pinned toolchain; fail instead when it is missing.

.PARAMETER Quiet
    Suppress progress output (errors are always shown).

.PARAMETER Json
    Also emit the machine-readable report to stdout.

.PARAMETER NoWrite
    Do not write the report under artifacts/.

.EXAMPLE
    pwsh -NoProfile -File tools/gen.ps1
    powershell -NoProfile -ExecutionPolicy Bypass -File tools/gen.ps1 -DataDir data -OutDir $env:TEMP\ps-gen

.NOTES
    Exit codes (same contract as tools/doctor.ps1 and tools/test.ps1):
      0 = generation succeeded
      1 = Luban or protoc rejected the input
      2 = the tool itself could not run (missing tools, missing data)
#>
[CmdletBinding()]
param(
    [string]$DataDir = '',
    [string]$OutDir = '',
    [switch]$SkipBootstrap,
    [switch]$Quiet,
    [switch]$Json,
    [switch]$NoWrite
)

$ErrorActionPreference = 'Continue'
$ProgressPreference = 'SilentlyContinue'

$script:Root = Split-Path -Parent $PSScriptRoot
$script:DataDir = if ($DataDir) { $DataDir } else { Join-Path $script:Root 'data' }
$script:OutDir = $OutDir
$script:ArtifactDir = Join-Path $script:Root 'artifacts\config'
$script:Steps = New-Object System.Collections.ArrayList

function Add-Step {
    param([string]$Name, [string]$Status, [string]$Detail = '')
    [void]$script:Steps.Add([pscustomobject]@{ Name = $Name; Status = $Status; Detail = $Detail })
    if (-not $Quiet) {
        $color = switch ($Status) { 'PASS' { 'Green' } 'FAIL' { 'Red' } default { 'DarkGray' } }
        Write-Host ('  [{0}] {1,-22} {2}' -f $Status, $Name, $Detail) -ForegroundColor $color
    }
}

function Invoke-Native {
    param([Parameter(Mandatory)][string]$FilePath, [string[]]$Arguments = @(), [string]$StdErrPath = '')
    if ($StdErrPath) {
        $out = & $FilePath @Arguments 2>$StdErrPath
        $code = $LASTEXITCODE
        $err = if (Test-Path -LiteralPath $StdErrPath) { Get-Content -LiteralPath $StdErrPath -Raw } else { '' }
        return [pscustomobject]@{ Code = $code; Output = (($out | Out-String).Trim()); Error = ([string]$err).Trim() }
    }

    $out = & $FilePath @Arguments 2>&1
    $code = $LASTEXITCODE
    return [pscustomobject]@{ Code = $code; Output = (($out | Out-String).Trim()); Error = '' }
}

function Get-Sha256Bytes {
    param([byte[]]$Bytes)
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try { return ([System.BitConverter]::ToString($sha.ComputeHash($Bytes))).Replace('-', '') }
    finally { $sha.Dispose() }
}

function Get-Sha256File {
    param([Parameter(Mandatory)][string]$Path)
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        $stream = [System.IO.File]::OpenRead($Path)
        try { $hash = $sha.ComputeHash($stream) } finally { $stream.Dispose() }
        return ([System.BitConverter]::ToString($hash)).Replace('-', '')
    }
    finally { $sha.Dispose() }
}

# Config hash: SHA-256 over the generated table bytes, in ordinal order of
# table name, as name + NUL + content. The hashed name is the loader key
# (`tbitem`), NOT the file name (`tbitem.bytes`): the two implementations share
# this hash, and ProjectSurvive.Data.Validator.ConfigHash only ever sees the keys
# Luban's generated Tables.cs registers. Keep the pair in step.
function Get-ConfigHash {
    param([Parameter(Mandatory)][string]$BytesDir)
    $files = @(Get-ChildItem -LiteralPath $BytesDir -Filter '*.bytes' | Sort-Object -Property Name)
    if ($files.Count -eq 0) { throw "no .bytes tables under $BytesDir" }

    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        foreach ($file in $files) {
            $tableName = [System.IO.Path]::GetFileNameWithoutExtension($file.Name)
            $nameBytes = [System.Text.Encoding]::UTF8.GetBytes($tableName)
            $content = [System.IO.File]::ReadAllBytes($file.FullName)
            $buffer = New-Object byte[] ($nameBytes.Length + 1 + $content.Length)
            [Array]::Copy($nameBytes, 0, $buffer, 0, $nameBytes.Length)
            $buffer[$nameBytes.Length] = 0
            [Array]::Copy($content, 0, $buffer, $nameBytes.Length + 1, $content.Length)
            [void]$sha.TransformBlock($buffer, 0, $buffer.Length, $null, 0)
        }

        [void]$sha.TransformFinalBlock((New-Object byte[] 0), 0, 0)
        return ([System.BitConverter]::ToString($sha.Hash)).Replace('-', '')
    }
    finally { $sha.Dispose() }
}

function Sync-Directory {
    param(
        [Parameter(Mandatory)][string]$Source,
        [Parameter(Mandatory)][string]$Destination,
        [Parameter(Mandatory)][string]$Filter
    )
    if (-not (Test-Path -LiteralPath $Destination)) {
        [void](New-Item -ItemType Directory -Path $Destination -Force)
    }

    Get-ChildItem -LiteralPath $Destination -Filter $Filter -File | Remove-Item -Force
    foreach ($file in Get-ChildItem -LiteralPath $Source -Filter $Filter -File) {
        Copy-Item -LiteralPath $file.FullName -Destination (Join-Path $Destination $file.Name) -Force
    }
}

# ---------------------------------------------------------------------------
# 0. prerequisites
# ---------------------------------------------------------------------------
if (-not (Test-Path -LiteralPath (Join-Path $script:DataDir 'luban.conf'))) {
    Write-Host ("ERROR: {0} does not contain luban.conf" -f $script:DataDir) -ForegroundColor Red
    exit 2
}

$confPath = Join-Path $script:DataDir 'luban.conf'
$protoDir = Join-Path $script:Root 'proto'
$protoFile = Join-Path $protoDir 'app.proto'

$toolsScript = Join-Path $PSScriptRoot 'setup-tools.ps1'
$lubanExe = Join-Path $PSScriptRoot 'vendor\luban\5.1.0\Luban\Luban.exe'
$protocExe = Join-Path $PSScriptRoot 'vendor\protoc\33.6\bin\protoc.exe'

if (-not (Test-Path -LiteralPath $lubanExe) -or -not (Test-Path -LiteralPath $protocExe)) {
    if ($SkipBootstrap) {
        Write-Host 'ERROR: pinned toolchain missing and -SkipBootstrap was passed' -ForegroundColor Red
        exit 2
    }
    if (-not $Quiet) { Write-Host 'Pinned toolchain missing - installing it first.' }
    $bootstrap = Invoke-Native -FilePath 'powershell' -Arguments @(
        '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $toolsScript
    )
    if ($bootstrap.Code -ne 0) {
        Write-Host ("ERROR: tools/setup-tools.ps1 failed (exit {0})" -f $bootstrap.Code) -ForegroundColor Red
        Write-Host $bootstrap.Output
        exit 2
    }
}

# The dotnet SDK is needed for nothing here, but Luban needs the .NET 8 runtime.
$runtimes = Invoke-Native -FilePath 'dotnet' -Arguments @('--list-runtimes')
if ($runtimes.Code -ne 0 -or $runtimes.Output -notmatch 'Microsoft\.NETCore\.App\s+([89]|\d{2})\.') {
    Write-Host 'ERROR: Luban needs a .NET 8+ runtime (dotnet --list-runtimes).' -ForegroundColor Red
    exit 2
}

# ---------------------------------------------------------------------------
# output layout
# ---------------------------------------------------------------------------
$staging = Join-Path ([System.IO.Path]::GetTempPath()) ('ps-gen-' + [System.Guid]::NewGuid().ToString('N'))
$stagingCs = Join-Path $staging 'cs'
$stagingData = Join-Path $staging 'data'

if ($script:OutDir) {
    $codeDir = Join-Path $script:OutDir 'Luban'
    $testDataDir = Join-Path $script:OutDir 'data'
    $unityDataDir = ''
    $protoOutDir = Join-Path $script:OutDir 'Proto'
}
else {
    $codeDir = Join-Path $script:Root 'lib\Runtime\Generated\Luban'
    $testDataDir = Join-Path $script:Root 'lib\Tests~\data'
    $unityDataDir = Join-Path $script:Root 'UnityProject\Assets\Main\Resources\Config'
    $protoOutDir = Join-Path $script:Root 'lib\Runtime\Generated\Proto'
}

foreach ($dir in @($stagingCs, $stagingData, $codeDir, $testDataDir, $protoOutDir)) {
    if (-not (Test-Path -LiteralPath $dir)) { [void](New-Item -ItemType Directory -Path $dir -Force) }
}
if ($unityDataDir -and -not (Test-Path -LiteralPath $unityDataDir)) {
    [void](New-Item -ItemType Directory -Path $unityDataDir -Force)
}

if (-not $Quiet) {
    Write-Host ''
    Write-Host 'ProjectSurvive - static data generation (Stage 02)' -ForegroundColor Cyan
    Write-Host ('=' * 72)
    Write-Host ("  data   : {0}" -f ($confPath.Replace($script:Root + '\', '')))
    Write-Host ("  code   : {0}" -f ($codeDir.Replace($script:Root + '\', '')))
    Write-Host ("  tables : {0}" -f ($testDataDir.Replace($script:Root + '\', '')))
    if ($unityDataDir) { Write-Host ("           {0}" -f ($unityDataDir.Replace($script:Root + '\', ''))) }
}

$exitCode = 0
try {
    # -----------------------------------------------------------------------
    # 1. Luban: schema + data -> C# + .bytes
    # -----------------------------------------------------------------------
    $lubanErr = Join-Path $staging 'luban.err.log'
    $luban = Invoke-Native -FilePath $lubanExe -Arguments @(
        '--conf', $confPath,
        '-t', 'client',
        '-c', 'cs-bin',
        '-d', 'bin',
        '--strict',
        '--errorFormat', 'json',
        '-x', ("outputCodeDir=" + $stagingCs),
        '-x', ("outputDataDir=" + $stagingData)
    ) -StdErrPath $lubanErr

    if ($luban.Code -ne 0) {
        Add-Step 'luban generate' 'FAIL' ("exit {0}" -f $luban.Code)
        Write-Host ''
        Write-Host 'Luban rejected the input:' -ForegroundColor Red
        Write-Host $luban.Output
        exit 1
    }

    $generatedCs = @(Get-ChildItem -LiteralPath $stagingCs -Filter '*.cs' -File)
    $generatedBytes = @(Get-ChildItem -LiteralPath $stagingData -Filter '*.bytes' -File)
    Add-Step 'luban generate' 'PASS' ("{0} .cs, {1} .bytes" -f $generatedCs.Count, $generatedBytes.Count)

    # -----------------------------------------------------------------------
    # 2. publish the generated C# (tracked: verify-generated diffs it)
    # -----------------------------------------------------------------------
    Sync-Directory -Source $stagingCs -Destination $codeDir -Filter '*.cs'
    Add-Step 'publish code' 'PASS' $codeDir.Replace($script:Root + '\', '')

    # -----------------------------------------------------------------------
    # 3. config hash -> build metadata
    # -----------------------------------------------------------------------
    $configHash = Get-ConfigHash -BytesDir $stagingData
    $lubanVersionLine = (& $lubanExe '--version' 2>&1 | Out-String)
    $lubanVersion = if ($lubanVersionLine -match 'Luban\s+([0-9][^\s+]*)') { $Matches[1] } else { '5.1.0' }

    $metadata = @"
//------------------------------------------------------------------------------
// <auto-generated>
//     Generated by tools/gen.ps1. Do not edit.
//     Config hash over the .bytes tables produced from data/.
// </auto-generated>
//------------------------------------------------------------------------------

namespace ProjectSurvive.Config
{
    /// <summary>Build metadata for the static data this assembly was generated from.</summary>
    public static class ConfigBuildMetadata
    {
        /// <summary>SHA-256 (upper-case hex) over the generated table bytes, in name order.</summary>
        public const string ConfigHash = "$configHash";

        /// <summary>Luban CLI version that produced the generated readers.</summary>
        public const string LubanVersion = "$lubanVersion";

        /// <summary>Schema revision of data/Defines. Bump when a field is added or renamed.</summary>
        public const int SchemaVersion = 2;
    }
}
"@
    $metadataPath = Join-Path $codeDir 'ConfigBuildMetadata.g.cs'
    [System.IO.File]::WriteAllText($metadataPath, $metadata, (New-Object System.Text.UTF8Encoding($false)))
    Add-Step 'config hash' 'PASS' ("{0}..." -f $configHash.Substring(0, 16))

    # -----------------------------------------------------------------------
    # 4. publish the .bytes tables (git-ignored, reproducible)
    # -----------------------------------------------------------------------
    Sync-Directory -Source $stagingData -Destination $testDataDir -Filter '*.bytes'
    if ($unityDataDir) {
        Sync-Directory -Source $stagingData -Destination $unityDataDir -Filter '*.bytes'
    }
    Add-Step 'publish tables' 'PASS' ("{0} file(s)" -f $generatedBytes.Count)

    # -----------------------------------------------------------------------
    # 5. protoc: proto/app.proto -> Generated/Proto/App.cs
    # -----------------------------------------------------------------------
    if (Test-Path -LiteralPath $protoFile) {
        $protoFiles = @(Get-ChildItem -LiteralPath $protoDir -Filter '*.proto' -File | Sort-Object -Property Name |
                ForEach-Object { $_.FullName })
        $protocArgs = @('--proto_path', $protoDir, ('--csharp_out=' + $protoOutDir)) + $protoFiles
        $protoc = Invoke-Native -FilePath $protocExe -Arguments $protocArgs

        if ($protoc.Code -ne 0) {
            Add-Step 'protoc' 'FAIL' ("exit {0}" -f $protoc.Code)
            Write-Host $protoc.Output -ForegroundColor Red
            Write-Host $protoc.Error -ForegroundColor Red
            exit 1
        }

        $protoOutputs = @(Get-ChildItem -LiteralPath $protoOutDir -Filter '*.cs' -File | Sort-Object -Property Name)
        Add-Step 'protoc' 'PASS' (($protoOutputs | ForEach-Object { $_.Name }) -join ', ')
    }
    else {
        Add-Step 'protoc' 'SKIP' ("{0} not found" -f $protoFile.Replace($script:Root + '\', ''))
    }

    # -----------------------------------------------------------------------
    # report
    # -----------------------------------------------------------------------
    if (-not $Quiet) {
        Write-Host ('=' * 72)
        Write-Host ("  configHash: {0}" -f $configHash)
        Write-Host '  RESULT: OK' -ForegroundColor Green
        Write-Host ''
    }

    $report = [pscustomobject]@{
        tool          = 'gen.ps1'
        stage         = '02'
        generatedAt   = (Get-Date).ToString('o')
        machine       = $env:COMPUTERNAME
        dataDir       = $script:DataDir
        codeDir       = $codeDir
        tableDirs     = @($testDataDir, $unityDataDir) | Where-Object { $_ }
        configHash    = $configHash
        lubanVersion  = $lubanVersion
        tables        = @($generatedBytes | ForEach-Object { $_.Name })
        exitCode      = $exitCode
        steps         = @($script:Steps)
    }

    if ($Json) { $report | ConvertTo-Json -Depth 6 }
    if (-not $NoWrite) {
        try {
            if (-not (Test-Path -LiteralPath $script:ArtifactDir)) {
                [void](New-Item -ItemType Directory -Path $script:ArtifactDir -Force)
            }
            $report | ConvertTo-Json -Depth 6 |
                Set-Content -LiteralPath (Join-Path $script:ArtifactDir 'gen-report.json') -Encoding UTF8
        }
        catch {
            Write-Host ("  (warning) could not write gen-report.json: {0}" -f $_.Exception.Message) -ForegroundColor Yellow
        }
    }
}
catch {
    Write-Host ("ERROR: {0}" -f $_.Exception.Message) -ForegroundColor Red
    $exitCode = 2
}
finally {
    if (Test-Path -LiteralPath $staging) { Remove-Item -LiteralPath $staging -Recurse -Force -ErrorAction SilentlyContinue }
}

exit $exitCode
